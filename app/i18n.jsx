/* hook: returns a t() fn and re-renders the component on language change */
function useT() {
  const [, force] = React.useState(0);
  React.useEffect(() => {
    const fn = () => force((x) => x + 1);
    I18n.listeners.add(fn);
    return () => I18n.listeners.delete(fn);
  }, []);
  return React.useCallback((k) => I18n.t(k), []);
}

Object.assign(window, { CF_DICT, CF_LANGS, CF_LOCALE, I18n, useT, tOpt, CF_OPT_KEY });
